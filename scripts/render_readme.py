#!/usr/bin/env python3
"""Render README.md from profile config and locally generated assets."""

from __future__ import annotations

import argparse
import html
import sys
from pathlib import Path

from common import setup_logging
from config import (
    ABOUT,
    CANVAS_WIDTH,
    CASE_STUDIES,
    COMPANY,
    CONTACT,
    FOUNDER_THESIS,
    FRAMEWORKS,
    LANGUAGES,
    NAME,
    POSITIONING,
    RESEARCH_INTERESTS,
    ROLE,
    ROOT,
)

logger = setup_logging("render_readme")


def picture(dark: str, light: str, alt: str, width: int = CANVAS_WIDTH) -> str:
    """Return GitHub-compatible paired theme artwork."""
    safe_alt = html.escape(alt, quote=True)
    return (
        "<picture>\n"
        f'  <source media="(prefers-color-scheme: dark)" srcset="{dark}">\n'
        f'  <source media="(prefers-color-scheme: light)" srcset="{light}">\n'
        f'  <img src="{dark}" width="{width}" alt="{safe_alt}">\n'
        "</picture>"
    )


def project_block(project: dict[str, object]) -> str:
    """Return a linked, themed project card."""
    slug = str(project["slug"])
    name = str(project["name"])
    url = html.escape(str(project["url"]), quote=True)
    art = picture(
        f"./assets/projects/{slug}-dark.svg",
        f"./assets/projects/{slug}-light.svg",
        f"{name} selected project architecture and technical stack",
    )
    return f'<a href="{url}">\n{art}\n</a>'


def render() -> str:
    """Compose the complete profile README."""
    projects = "\n\n<br>\n\n".join(project_block(project) for project in CASE_STUDIES)
    research = " · ".join(RESEARCH_INTERESTS)
    languages = " · ".join(LANGUAGES)
    frameworks = " · ".join(FRAMEWORKS)
    company_url = CONTACT["company"]
    email = CONTACT["email"]

    hero = picture(
        "./assets/hero-dark.svg",
        "./assets/hero-light.svg",
        f"{NAME}, {ROLE} at {COMPANY} — spatial intelligence profile",
    )
    capabilities = picture(
        "./assets/capabilities-dark.svg",
        "./assets/capabilities-light.svg",
        "Engineering capability matrix across computer vision, spatial XR, and AI systems",
    )
    research_art = picture(
        "./assets/research-dark.svg",
        "./assets/research-light.svg",
        "Research trajectory from computer vision to 3D intelligence, agents, and spatial systems",
    )
    telemetry = picture(
        "./assets/contribution-dark.svg",
        "./assets/contribution-light.svg",
        "GitHub contribution build telemetry refreshed daily",
    )

    return f"""<div align="center">

<!--
  Generated by scripts/render_readme.py.
  Edit config.py, then run: python scripts/generate_all.py --skip-photo
-->

{hero}

<br>

### Spatial intelligence, engineered into products.

{html.escape(POSITIONING)}

<sub>{html.escape(FOUNDER_THESIS)}</sub>

</div>

<br>

## Selected systems

Not a list of repositories—a small set of systems that show how I think, architect, and ship.

{projects}

<br>

## Engineering range

{capabilities}

<br>

## Research trajectory

{research_art}

<div align="center">
<sub>{html.escape(research)}</sub>
</div>

<br>

## Build telemetry

{telemetry}

<br>

## Operating stack

**Languages** — {html.escape(languages)}

**Systems & frameworks** — {html.escape(frameworks)}

**Current focus** — Gaussian Splatting · 3D Reconstruction · Spatial AI · Robotics · AI Agents

<br>

## About the work

I am **{html.escape(NAME)}**, {html.escape(ROLE)} at
[{html.escape(COMPANY)}]({company_url}). {html.escape(ABOUT)}

My work sits at the boundary between research and product: perception systems,
real-time spatial interfaces, multimodal AI, and autonomous software that can
observe a system, reason about it, and take useful action.

<br>

## Build with me

I am interested in ambitious collaborations across spatial computing,
computer vision, real-time 3D, robotics, and agentic AI.

[{html.escape(COMPANY)}]({company_url}) ·
[GitHub](https://github.com/kenzzhood) ·
[Email](mailto:{email})

<br>

<div align="center">

<sub><code>research → prototype → product → iterate</code></sub>

</div>

<details>
<summary>How this profile works</summary>

This profile is generated locally with Python and self-contained SVG. It uses
no JavaScript and no hosted GitHub-stat widgets. Public contribution data is
refreshed daily by GitHub Actions.

```bash
python -m venv .venv
source .venv/bin/activate
pip install -r requirements.txt
python scripts/generate_all.py
```

See [architecture](docs/ARCHITECTURE.md) and
[development](docs/DEVELOPMENT.md).

</details>
"""


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--output",
        type=Path,
        default=ROOT / "README.md",
    )
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)
    try:
        content = render()
        args.output.write_text(content, encoding="utf-8")
        logger.info("wrote %s (%d bytes)", args.output, len(content))
    except OSError as exc:
        logger.error("failed to write README: %s", exc)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
